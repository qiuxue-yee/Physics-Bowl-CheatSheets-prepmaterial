"""Generate the links used in both books from the shared topic map."""
from __future__ import annotations

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/problem-topics.json"
SOURCES = ROOT / "data/problem-sources.json"
OUTPUT = ROOT / "tex/crossrefs.tex"


def generate() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    units = data["units"]
    ids = {unit["id"] for unit in units}
    problems = data["problems"]
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    if len(ids) != 12 or set(problems) != {str(i) for i in range(1, 40)}:
        raise ValueError("The topic map must contain 12 unique units and problems 1–39.")
    if any(not refs or len(refs) != len(set(refs)) or not set(refs) <= ids
           for refs in problems.values()):
        raise ValueError("Every problem needs valid, non-duplicate unit links.")
    if set(sources) != set(problems):
        raise ValueError("Every selected problem needs a source entry.")
    lines = [
        "% Generated by scripts/generate_crossrefs.py; edit data/problem-topics.json.",
        r"\newcommand{\SelectedProblem}[1]{\hyperref[p-prob:#1]{Problem~#1}"
        r" (p.~\pageref{p-prob:#1})}",
        r"\newcommand{\GuideUnit}[2]{\hyperref[g-unit:#1]{#2}}",
        r"\newcommand{\UnitProblemLinks}[1]{\par\smallskip\noindent"
        r"\textbf{Related problems:} \csname problem-links-#1\endcsname\par}",
        r"\newcommand{\StudyGuideLinks}[1]{\par\smallskip\noindent"
        r"\textit{Study guide:} \csname guide-links-#1\endcsname\par}",
        r"\newcommand{\LocalProblem}[1]{\hyperref[prob:#1]{#1}}",
        r"\newcommand{\ProblemSource}[1]{\par\noindent{\footnotesize "
        r"\textit{Source:} \csname source-#1\endcsname}\par}",
    ]
    titles = {unit["id"]: unit["title"] for unit in units}
    for unit in units:
        linked = [int(number) for number, refs in problems.items()
                  if unit["id"] in refs]
        value = ", ".join(r"\SelectedProblem{" + str(n) + "}" for n in linked)
        if not value:
            value = "No selected problems in this unit yet."
        lines.append(r"\expandafter\def\csname problem-links-" + unit["id"]
                     + r"\endcsname{" + value + "}")
    for number in range(1, 40):
        value = "; ".join(r"\GuideUnit{" + uid + "}{" + titles[uid] + "}"
                          for uid in problems[str(number)])
        lines.append(r"\expandafter\def\csname guide-links-" + str(number)
                     + r"\endcsname{" + value + "}")
        source = sources[str(number)]
        if not all(source.get(k) for k in ("year", "question", "pdf_page", "url")):
            raise ValueError(f"Incomplete source for problem {number}")
        citation = (r"\href{" + source["url"] + "}{AAPT PhysicsBowl "
                    + str(source["year"]) + ", problem " + str(source["question"])
                    + " (PDF p.~" + str(source["pdf_page"]) + ")}")
        lines.append(r"\expandafter\def\csname source-" + str(number)
                     + r"\endcsname{" + citation + "}")
    lines.append(r"\newcommand{\ProblemTopicIndex}{%")
    lines.append(r"\begin{itemize}[leftmargin=*]")
    for unit in units:
        linked = [int(number) for number, refs in problems.items()
                  if unit["id"] in refs]
        value = ", ".join(r"\LocalProblem{" + str(n) + "}" for n in linked)
        if not value:
            value = "no selected problems"
        lines.append(r"\item \GuideUnit{" + unit["id"] + "}{" + unit["title"]
                     + "}: " + value)
    lines.append(r"\end{itemize}}")
    return "\n".join(lines) + "\n"


def main() -> None:
    text = generate()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("Cross-references are stale; run python scripts/generate_crossrefs.py")
        print("Cross-references match the topic map.")
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
